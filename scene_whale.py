"""Scene 2 — BATHTUB WHALE.

A humpback whale breaching out of a bathtub: water exploding
everywhere, white bathroom tiles, a rubber duck flying, morning
window light, soap bubbles.

Draws onto a render.Canvas. Pure standard library.
"""

import math

from render import Canvas


def _radius_profile(t):
    """Whale body radius along the spine: tail, fat belly, round head."""
    keys = [(0.00, 30), (0.15, 76), (0.45, 102), (0.65, 92),
            (0.85, 78), (1.00, 62)]
    for i in range(len(keys) - 1):
        t0, r0 = keys[i]
        t1, r1 = keys[i + 1]
        if t0 <= t <= t1:
            f = (t - t0) / (t1 - t0)
            return r0 + (r1 - r0) * f
    return keys[-1][1]


